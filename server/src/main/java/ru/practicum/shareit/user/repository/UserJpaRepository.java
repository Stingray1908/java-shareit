package ru.practicum.shareit.user.repository;

import org.springframework.data.jpa.repository.JpaRepository;
import ru.practicum.shareit.user.User;

import java.util.List;
import java.util.Optional;

/**
 * JPA‑репозиторий для работы с сущностями пользователей в базе данных.
 * Расширяет стандартный JpaRepository Spring Data JPA, добавляя специализированные методы для бизнес‑логики.
 *
 * <p>
 * Основные функции:
 * - CRUD‑операции (наследуются от JpaRepository);
 * - проверка уникальности email перед созданием/обновлением пользователя;
 * - поиск пользователей по ID и получение списка всех пользователей.
 *
 * <p>
 * Ключевые методы:
 * - existsByEmail — проверяет, существует ли пользователь с указанным email (используется для валидации уникальности);
 * - findById — находит пользователя по ID, возвращает Optional для безопасной обработки отсутствующих записей;
 * - findAll — возвращает список всех пользователей в системе;
 * - deleteById — удаляет пользователя по ID;
 * - deleteAll — удаляет ВСЕХ пользователей (используется с осторожностью, например, в тестах).
 * <p>
 * Особенности реализации:
 * - использует аннотации Spring Data JPA для автоматической генерации SQL‑запросов;
 * - возвращает Optional/List для безопасной работы с результатами запросов;
 * - интегрируется с транзакционным менеджментом Spring через @Transactional в сервисе.
 */
public interface UserJpaRepository extends JpaRepository<User, Long> {

    /**
     * Проверяет, существует ли пользователь с указанным email в системе.
     * Используется для валидации уникальности email при создании/обновлении пользователя.
     *
     * @param email email для проверки
     * @return true, если пользователь с таким email существует; false — если не существует
     */
    boolean existsByEmail(String email);

    /**
     * Находит пользователя по его уникальному идентификатору.
     *
     * @param id ID пользователя
     * @return Optional с сущностью пользователя, если найден; пустой Optional — если не найден
     */
    Optional<User> findById(Long id);

    /**
     * Возвращает список всех пользователей, хранящихся в базе данных.
     *
     * @return список сущностей пользователей
     */
    List<User> findAll();

    /**
     * Удаляет пользователя по его уникальному идентификатору.
     *
     * @param id ID пользователя для удаления
     */
    void deleteById(Long id);
}

