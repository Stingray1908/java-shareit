                                        'APPROVED',
                                        'REJECTED',
                                        'CANCELLED',
                                        'COMPLETED');
EXCEPTION
    WHEN duplicate_object THEN
        -- Тип уже существует, продолжаем выполнение
        NULL;
END $$;
